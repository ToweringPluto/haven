"""Generate ``data/seed/properties.yaml``: 11 fictional, illustrative Edinburgh properties.

Nothing here is a real listing. What is and isn't fictional:

* **Fictional, chosen by hand:** rents, bedrooms, floor areas, floor levels, lifts, entrance
  steps, council tax bands and other recurring costs. They are illustrative asking values for
  a demo, not statistics (rent context comes from a separate reference, task P2-02).
* **Drawn from data:** EPC band, property type (where not fixed by an edge case) and main
  heating fuel are sampled with a fixed random seed, weighted by the number of City of
  Edinburgh EPC certificates in each (band × type × fuel) group of
  ``data/reference/energy_kwh_per_m2_edinburgh.yaml``.
* **Real:** the coordinates are points on real public streets (OpenStreetMap, looked up with
  Nominatim on the date in ``COORDINATES_RETRIEVED``). They are street points, not buildings,
  and no house numbers are used anywhere.

Usage (from the repo root)::

    uv run --directory backend python scripts/make_seed.py          # (re)write the file
    uv run --directory backend python scripts/make_seed.py --check  # fail if it is stale
"""

