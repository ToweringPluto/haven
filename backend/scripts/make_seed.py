def ev(value: Any, note: str) -> dict[str, Any]:
    """Listing-origin Evidence; a ``None`` value is 'insufficient', never a default."""
    return {
        "value": value,
        "origin": "listing",
        "source": SOURCE,
        "as_of": GENERATED_ON.isoformat(),
        "status": "insufficient" if value is None else "known",
        "note": note,
    }


def draw_group(
    rng: random.Random,
    groups: list[DetailGroup],
    property_type: str | None,
    epc_band: str | None,
) -> DetailGroup:
    """A (band, type, fuel) group, weighted by certificate count, matching any fixed fields."""
    candidates = [
        g
        for g in groups
        if g.property_type.value in DRAWABLE_TYPES
        and (property_type is None or g.property_type.value == property_type)
        and (epc_band is None or g.epc_band.value == epc_band)
    ]
    if not candidates:
        raise ValueError(f"no EPC group for type={property_type} band={epc_band}")
    return rng.choices(candidates, weights=[g.n for g in candidates], k=1)[0]


def build_property(spec: Spec, group: DetailGroup) -> Property:
    ptype = group.property_type.value
    stacked = ptype in ("flat", "maisonette")
    words = " ".join(w for w in (spec.descriptor, ptype) if w)
    title = f"{ILLUSTRATIVE_TITLE_PREFIX}: {spec.bedrooms}-bed {words}, {spec.area}"

    def note(name: str, *, drawn: bool = False) -> str:
        if spec.edge_case and name in spec.edge_fields:
            return NOTE_EDGE.format(case=spec.edge_case)
        return NOTE_DRAWN if drawn else NOTE_FICTIONAL

    lift_note = (
        "The listing doesn't say whether there is a lift; check with the letting agent."
        if spec.has_lift is None
        else note("has_lift")
    )
    band_note = (
        "The listing doesn't state the council tax band; check the Scottish Assessors portal."
        if spec.council_tax_band is None
        else note("council_tax_band")
    )
    return Property.model_validate(
        {
            "id": f"seed-prop-{spec.slug}",
            "title": title,
            "illustrative": True,
            "area": spec.area,
            "latitude": spec.latitude,
            "longitude": spec.longitude,
            "rent_pcm_gbp": ev(spec.rent_pcm_gbp, note("rent_pcm_gbp")),
            "bedrooms": ev(spec.bedrooms, note("bedrooms")),
            "property_type": ev(ptype, note("property_type", drawn=spec.property_type is None)),
            "floor_area_m2": ev(spec.floor_area_m2, note("floor_area_m2")),
            "council_tax_band": ev(spec.council_tax_band, band_note),
            "epc_rating": ev(group.epc_band.value, note("epc_rating", drawn=spec.epc_band is None)),
            "main_fuel": ev(group.main_fuel.value, note("main_fuel", drawn=True)),
            "floor_level": ev(spec.floor_level if stacked else 0, note("floor_level")),
            "has_lift": ev(spec.has_lift if stacked else False, lift_note),
            "entrance_steps": ev(spec.entrance_steps, note("entrance_steps")),
            "other_recurring_costs": [
                {"label": label, "monthly_gbp": ev(gbp, NOTE_FICTIONAL)}
                for label, gbp in spec.other_costs
            ],
        }
    )


def build_seed() -> SeedFile:
    model = load_energy_model()
    rng = random.Random(RANDOM_SEED)
    properties = [
        build_property(spec, draw_group(rng, model.groups, spec.property_type, spec.epc_band))
        for spec in SPECS
    ]
    return SeedFile.model_validate(
        {
            "meta": {
                "generated_by": "backend/scripts/make_seed.py",
                "generated_on": GENERATED_ON,
                "random_seed": RANDOM_SEED,
                "notes": (
                    f"All {len(SPECS)} properties are FICTIONAL ('Illustrative property — not a "
                    "real listing'). Rents, bedrooms, floor areas, floors, lifts, steps, "
                    "council tax bands and other costs are hand-chosen illustrative values, "
                    "not statistics. "
                    "EPC band, main fuel and (where no edge case fixes it) property type are "
                    "drawn with the fixed random seed, weighted by Edinburgh EPC certificate "
                    "counts. Coordinates are points on real public streets (no house numbers)."
                ),
                "epc_distribution_source": f"data/reference/{ENERGY_MODEL_FILE}.yaml "
                f"({model.meta.source_url}, release {model.dataset_release})",
                "coordinates_source": (
                    "OpenStreetMap street ways, rounded to 5 decimal places. First 8: point from "
                    "Nominatim search (https://nominatim.openstreetmap.org/), retrieved "
                    "2026-11-07. The rest: way centre from Overpass, 2026-11-08; "
                    "OSM way ids: " + ", ".join(f"{s.street} (way {s.osm_way})" for s in SPECS)
                ),
                "coordinates_licence": "© OpenStreetMap contributors, ODbL 1.0 "
                "(https://www.openstreetmap.org/copyright)",
                "coordinates_retrieved": COORDINATES_RETRIEVED,
                "edge_cases": {f"seed-prop-{s.slug}": s.edge_case for s in SPECS if s.edge_case},
            },
            "properties": properties,
        }
    )


def render(seed: SeedFile) -> str:
    body = yaml.safe_dump(
        seed.model_dump(mode="json"), sort_keys=False, allow_unicode=True, width=100
    )
    return HEADER + body


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    parser.add_argument("--output", type=Path, default=SEED_PATH)
    args = parser.parse_args(argv)

    text = render(build_seed())
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else None
        if current != text:
            print(f"{args.output} is stale; run scripts/make_seed.py", file=sys.stderr)
            return 1
        print(f"{args.output} is up to date")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
