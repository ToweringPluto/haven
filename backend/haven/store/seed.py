"""Seed property store: the fictional illustrative properties in ``data/seed/properties.yaml``.

The file is generated by ``backend/scripts/make_seed.py`` (never edit it by hand). Every
property in it is fictional and marked as such (``illustrative: true`` and a title starting
with :data:`ILLUSTRATIVE_TITLE_PREFIX`); the loader rejects anything else, so a real listing
can't slip in through the seed.
"""

from collections.abc import Iterator
from datetime import date
from pathlib import Path
from typing import Self

import yaml
from pydantic import BaseModel, ConfigDict, Field, ValidationError, model_validator

from haven.config import SEED_PATH
from haven.domain import Property

ILLUSTRATIVE_TITLE_PREFIX = "Illustrative property — not a real listing"


class SeedDataError(ValueError):
    """The seed file is missing, unreadable or doesn't match the schema."""


class SeedMeta(BaseModel):
    """Where the seed's values come from. Everything not listed here is fictional."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    generated_by: str = Field(min_length=1)
    generated_on: date
    random_seed: int
    notes: str = Field(min_length=1)
    epc_distribution_source: str = Field(
        min_length=1, description="Reference file the EPC band / type / fuel mix is drawn from."
    )
    coordinates_source: str = Field(min_length=1)
    coordinates_licence: str = Field(min_length=1)
    coordinates_retrieved: date
    edge_cases: dict[str, str] = Field(
        default_factory=dict, description="Property id → the deliberate edge case it covers."
    )


class SeedFile(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    meta: SeedMeta
    properties: list[Property] = Field(min_length=1)

    @model_validator(mode="after")
    def _check_properties(self) -> Self:
        ids = [p.id for p in self.properties]
        if len(set(ids)) != len(ids):
            raise ValueError("duplicate property id in seed")
        for p in self.properties:
            if not p.illustrative or not p.title.startswith(ILLUSTRATIVE_TITLE_PREFIX):
                raise ValueError(
                    f"seed property {p.id!r} must be illustrative and titled "
                    f"{ILLUSTRATIVE_TITLE_PREFIX!r}"
                )
        return self


class SeedStore:
    """Read-only access to the seed properties, in file order."""

    def __init__(self, seed: SeedFile) -> None:
        self.meta = seed.meta
        self._properties = {p.id: p for p in seed.properties}

    def __iter__(self) -> Iterator[Property]:
        return iter(self._properties.values())

    def __len__(self) -> int:
        return len(self._properties)

    def list(self) -> list[Property]:
        return list(self._properties.values())

    def get(self, property_id: str) -> Property | None:
        return self._properties.get(property_id)


def load_seed(path: Path | None = None) -> SeedStore:
    """Load and validate the seed file (default ``data/seed/properties.yaml``)."""
    path = SEED_PATH if path is None else path
    try:
        raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise SeedDataError(f"cannot read seed file {path}: {exc}") from exc
    except yaml.YAMLError as exc:
        raise SeedDataError(f"invalid YAML in seed file {path}: {exc}") from exc
    try:
        return SeedStore(SeedFile.model_validate(raw))
    except ValidationError as exc:
        raise SeedDataError(f"seed file {path} does not match the schema: {exc}") from exc
