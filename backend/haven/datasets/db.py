"""Database side of the data layer (Tiger Cloud / TimescaleDB via ``haven.store.db``).

- :func:`load_rent_stats` applies ``data/sql/rent_stats.sql`` (generated by
  ``scripts/build_seeds.py``): it creates the ``rent_stats`` hypertable if needed and upserts
  every Lothian row, so running it again changes nothing.
- :func:`rent_series` reads the rent time series from the database when ``HAVEN_DATABASE_URL``
  is set, and from ``data/seed/private_rents.json`` otherwise (or when the database can't be
  reached), so the app still runs with no network. The result says which source it used.
"""

from typing import Any, Literal

from pydantic import BaseModel, ConfigDict
from sqlalchemy import Engine, text
from sqlalchemy.exc import SQLAlchemyError

from haven.datasets.loaders import rents
from haven.datasets.seeds import load_seed_file
from haven.store.db import DatabaseNotConfiguredError, get_engine

RENT_COLUMNS = [
    "brma",
    "beds",
    "period_end",
    "year",
    "lower_quartile_gbp_pcm",
    "median_gbp_pcm",
    "mean_gbp_pcm",
    "upper_quartile_gbp_pcm",
    "n_records",
    "is_sample",
]


class RentSeries(BaseModel):
    model_config = ConfigDict(frozen=True)

    source: Literal["database", "seed"]
    beds: str
    records: list[dict[str, Any]]


def load_rent_stats(engine: Engine | None = None) -> int:
    """Create/upsert the ``rent_stats`` hypertable. Returns the row count afterwards."""
    engine = engine or get_engine()
    sql = rents.SQL_PATH.read_text(encoding="utf-8")
    with engine.begin() as conn:
        conn.exec_driver_sql(sql)  # psycopg runs a parameterless multi-statement script
        count = conn.execute(text("select count(*) from rent_stats")).scalar_one()
    return int(count)


def _from_seed(beds: str) -> RentSeries:
    records = [
        {k: r[k] for k in RENT_COLUMNS}
        for r in load_seed_file(rents.DATASET_ID).records
        if r["beds"] == beds
    ]
    return RentSeries(source="seed", beds=beds, records=records)


def rent_series(beds: str, engine: Engine | None = None) -> RentSeries:
    """Lothian rent statistics for one bedroom category (e.g. ``"2_bed"``), oldest first."""
    if beds not in rents.BEDS.values():
        raise ValueError(f"unknown bedroom category {beds!r}")
    try:
        engine = engine or get_engine()
        with engine.connect() as conn:
            rows = conn.execute(
                text(
                    f"select {', '.join(RENT_COLUMNS)} from rent_stats "
                    "where brma = :brma and beds = :beds order by period_end"
                ),
                {"brma": rents.BRMA, "beds": beds},
            ).mappings()
            records = [_jsonable(dict(row)) for row in rows]
    except (DatabaseNotConfiguredError, SQLAlchemyError):
        return _from_seed(beds)
    if not records:
        return _from_seed(beds)  # table exists but hasn't been loaded yet
    return RentSeries(source="database", beds=beds, records=records)


def _jsonable(row: dict[str, Any]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for key, value in row.items():
        if hasattr(value, "isoformat"):
            value = value.isoformat()
        elif value is not None and key.endswith("_gbp_pcm"):
            value = float(value)  # numeric -> Decimal from Postgres
        out[key] = value
    return out
