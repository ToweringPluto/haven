"""Typed loader for ``data/datasets.yml``, the dataset registry.

One entry per dataset Haven uses. The registry is the single list that the "Data and limits"
page (``GET /v1/data-sources``) and the README dataset table are rendered from, so every entry
must say where the data comes from (``url``), on what terms (``licence_note``) and how current
it is (``as_of``). Loading fails loudly on a missing or malformed field.
"""

from datetime import date
from enum import StrEnum
from pathlib import Path
from typing import Self

import yaml
from pydantic import BaseModel, ConfigDict, Field, ValidationError, model_validator

from haven.config import DATASETS_REGISTRY_PATH


class RegistryError(Exception):
    """The registry is missing, unreadable or fails validation."""


class Integration(StrEnum):
    """How a dataset reaches the app."""

    hypertable = "hypertable"  # time series: seed JSON + TimescaleDB hypertable SQL
    seed_table = "seed_table"  # small table loaded from data/seed/<id>.json
    cached_api = "cached_api"  # fetched once by scripts/fetch_cached.py into data/cache/
    reference_json = "reference_json"  # guidance values in data/reference_json/<id>.json
    sample = "sample"  # invented data; every record is_sample=true


class Priority(StrEnum):
    P0 = "P0"
    P1 = "P1"
    P2 = "P2"


class DatasetEntry(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    id: str = Field(pattern=r"^[a-z][a-z0-9_]*$")
    name: str = Field(min_length=1)
    url: str = Field(pattern=r"^https?://\S+$", description="Where the data comes from.")
    licence_note: str = Field(min_length=1, description="Licence and required attribution.")
    as_of: date = Field(description="Date the figures describe (period, edition or snapshot).")
    retrieved_at: date = Field(description="Date the source was read; never in the future.")
    integration: Integration
    feature: str = Field(min_length=1, description="Which part of the app uses it.")
    priority: Priority
    caveats: list[str] = Field(min_length=1, description="Known limits, shown to users.")
    seed: str | None = Field(
        default=None, description="Repo-relative path of the offline seed or reference file."
    )

    @model_validator(mode="after")
    def _check_dates(self) -> Self:
        if self.retrieved_at > date.today():
            raise ValueError(f"{self.id}: retrieved_at {self.retrieved_at} is in the future")
        return self


class Registry(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    datasets: list[DatasetEntry] = Field(min_length=1)

    @model_validator(mode="after")
    def _unique_ids(self) -> Self:
        ids = [d.id for d in self.datasets]
        dupes = sorted({i for i in ids if ids.count(i) > 1})
        if dupes:
            raise ValueError(f"duplicate dataset id(s): {dupes}")
        return self

    def get(self, dataset_id: str) -> DatasetEntry:
        for entry in self.datasets:
            if entry.id == dataset_id:
                return entry
        raise KeyError(dataset_id)


TABLE_START = "<!-- datasets-table:start (generated by backend/scripts/render_registry.py) -->"
TABLE_END = "<!-- datasets-table:end -->"


def render_markdown_table(registry: Registry) -> str:
    """The registry as a Markdown table, for the README."""

    def cell(text: str) -> str:
        return text.replace("|", "\\|").replace("\n", " ")

    lines = [
        "| Dataset | Use | Integration | Priority | As of | Licence | Caveats |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for d in registry.datasets:
        lines.append(
            f"| [{cell(d.name)}]({d.url}) (`{d.id}`) | {cell(d.feature)} | "
            f"`{d.integration.value}` | {d.priority.value} | {d.as_of.isoformat()} | "
            f"{cell(d.licence_note)} | {cell(' '.join(d.caveats))} |"
        )
    return "\n".join(lines)


def replace_table(text: str, table: str) -> str:
    """Put ``table`` between the README's generated-table markers."""
    start, end = text.index(TABLE_START), text.index(TABLE_END)
    return text[: start + len(TABLE_START)] + "\n\n" + table + "\n\n" + text[end:]


def load_registry(path: Path | None = None) -> Registry:
    """Load and validate the registry (default ``data/datasets.yml``)."""
    path = DATASETS_REGISTRY_PATH if path is None else path
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise RegistryError(f"registry not found: {path}") from exc
    except yaml.YAMLError as exc:
        raise RegistryError(f"{path.name}: invalid YAML: {exc}") from exc
    try:
        return Registry.model_validate(data)
    except ValidationError as exc:
        raise RegistryError(f"{path.name}: {exc}") from exc
